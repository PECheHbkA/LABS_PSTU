#include <iostream>        // подключаем библиотеку для ввода-вывода (cout, cin)
#include <fstream>         // подключаем библиотеку для работы с файлами (ifstream, ofstream)
#include <string>          // подключаем библиотеку для работы со строками (string)
#include <clocale>         // подключаем библиотеку для русских букв в консоли

using namespace std;

// функция считает количество слов в строке
int countWords(string s) {                   // принимаем строку, возвращаем число
    int count = 0;                           // счётчик слов, изначально 0
    bool inWord = false;                     // флаг: находимся ли внутри слова
    for (int i = 0; i < s.length(); i++) {   // идём по всем символам строки
        if (s[i] != ' ' && s[i] != '\n' && s[i] != '\t') {  // если символ не пробел
            if (inWord == false) {           // если только что начали слово
                count++;                     // увеличиваем счётчик слов
                inWord = true;               // запоминаем, что мы внутри слова
            }
        } else {                             // иначе (встретили пробел)
            inWord = false;                  // значит слово закончилось
        }
    }
    return count;                            // возвращаем количество слов
}

// функция создаёт файл F1.txt с 10+ строками
void createF1() {
    ofstream f("F1.txt");               // открываем файл F1.txt для записи
    f << "Привет\n";                    // пишем первую строку (одно слово)
    f << "Это строка с несколькими словами\n";  // пишем вторую строку (много слов)
    f << "Слово\n";                     // пишем третью строку (одно слово)
    f << "Ещё одна длинная строка тут\n";        // пишем четвёртую строку (много слов)
    f << "Кот\n";                       // пишем пятую строку (одно слово)
    f << "Программирование\n";          // пишем шестую строку (одно слово)
    f << "Строка с пробелами внутри\n"; // пишем седьмую строку (много слов)
    f << "Дом\n";                       // пишем восьмую строку (одно слово)
    f << "Лабораторная работа по строкам\n";     // пишем девятую строку (много слов)
    f << "Солнце\n";                    // пишем десятую строку (одно слово)
    f << "ЕщёСлово\n";                  // пишем одиннадцатую строку (одно слово)
    f << "Последняя строка файла F1\n"; // пишем двенадцатую строку (много слов)
    f.close();                          // закрываем файл
    cout << "Файл F1.txt создан!" << endl;  // сообщаем пользователю
}

// функция копирует строки с одним словом из F1 в F2
void copyLines() {
    ifstream in("F1.txt");              // открываем F1.txt для чтения
    ofstream out("F2.txt");             // открываем F2.txt для записи
    string line;                        // переменная для хранения строки
    while (getline(in, line)) {         // читаем файл построчно
        if (countWords(line) == 1) {    // если в строке ровно одно слово
            out << line << endl;        // записываем эту строку в F2
        }
    }
    in.close();                         // закрываем F1
    out.close();                        // закрываем F2
    cout << "Строки с одним словом скопированы!" << endl;  // сообщаем
}

// функция ищет самое длинное слово в F2
void findLongest() {
    ifstream f("F2.txt");               // открываем F2.txt для чтения
    string line;                        // переменная для строки
    string longest = "";                // тут будем хранить самое длинное слово
    while (getline(f, line)) {          // читаем файл построчно
        string word = "";               // переменная для текущего слова
        for (int i = 0; i <= line.length(); i++) {  // идём по строке
            if (i < line.length() && line[i] != ' ') {  // если не пробел
                word = word + line[i];  // добавляем символ к слову
            } else {                    // если пробел или конец строки
                if (word.length() > longest.length()) {  // если слово длиннее
                    longest = word;     // запоминаем его как самое длинное
                }
                word = "";              // обнуляем слово для следующего
            }
        }
    }
    f.close();                          // закрываем файл
    cout << "Самое длинное слово: " << longest << endl;  // выводим результат
    cout << "Его длина: " << longest.length() << endl;   // выводим длину
}

int main() {                            // главная функция
    setlocale(LC_ALL, "Russian");       // включаем русский язык в консоли
    createF1();                         // создаём файл F1
    copyLines();                        // копируем строки в F2
    findLongest();                      // ищем самое длинное слово
    return 0;                           // завершаем программу
}